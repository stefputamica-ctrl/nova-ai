    def light_rays(self, a0, a1, n, maxd):
        out = []
        for i in range(n + 1):
            a = a0 + (a1 - a0) * i / n
            out.append((a, self.ray(self.px, self.py, a, maxd)))
        return out

    def draw_darkness(self):
        sw, sh = W // LOWRES + 2, H // LOWRES + 2
        if not hasattr(self, "dark"):
            self.dark = pygame.Surface((sw, sh), pygame.SRCALPHA)
        dark = self.dark
        dark.fill((0, 0, 0, 252))
        psx, psy = self.w2s(self.px, self.py)
        cx, cy = psx / LOWRES, psy / LOWRES
        tl = TILE / LOWRES

        def pts(rays, limit, center):
            p = [(cx, cy)] if center else []
            for a, d in rays:
                d = min(d, limit)
                p.append((cx + math.cos(a) * d * tl, cy + math.sin(a) * d * tl))
            return p

        on = self.light_on()
        amb = self.light_rays(0, 2 * math.pi, 28, 2.3)
        pygame.draw.polygon(dark, (0, 0, 0, 175 if on else 195), pts(amb, 2.3, False))
        if on:
            cone = self.light_rays(self.dir - LIGHT_HALF, self.dir + LIGHT_HALF, 36, LIGHT_RANGE)
            pygame.draw.polygon(dark, (0, 0, 0, 105), pts(cone, LIGHT_RANGE, True))
            pygame.draw.circle(dark, (0, 0, 0, 90), (int(cx), int(cy)), int(tl * 0.7))
            pygame.draw.polygon(dark, (0, 0, 0, 45), pts(cone, LIGHT_RANGE * 0.62, True))
            pygame.draw.polygon(dark, (0, 0, 0, 5), pts(cone, LIGHT_RANGE * 0.32, True))
        else:
            pygame.draw.circle(dark, (0, 0, 0, 170), (int(cx), int(cy)), int(tl * 0.8))
        screen.blit(pygame.transform.smoothscale(dark, (sw * LOWRES, sh * LOWRES)), (0, 0))

