def make_maze():
    g = [[1] * COLS for _ in range(ROWS)]
    stack = [(1, 1)]
    g[1][1] = 0
    while stack:
        x, y = stack[-1]
        options = []
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            nx, ny = x + dx, y + dy
            if 0 < nx < COLS - 1 and 0 < ny < ROWS - 1 and g[ny][nx] == 1:
                options.append((nx, ny, dx, dy))
        if options:
            nx, ny, dx, dy = random.choice(options)
            g[y + dy // 2][x + dx // 2] = 0
            g[ny][nx] = 0
            stack.append((nx, ny))
        else:
            stack.pop()
    # a few rooms
    for _ in range(4):
        rx = random.randrange(1, COLS - 4, 2)
        ry = random.randrange(1, ROWS - 4, 2)
        for yy in range(ry, ry + 3):
            for xx in range(rx, rx + 3):
                g[yy][xx] = 0
    # knock out walls so there are loops to escape through
    for _ in range(COLS * ROWS // 10):
        x = random.randrange(1, COLS - 1)
        y = random.randrange(1, ROWS - 1)
        if g[y][x] == 1:
            horiz = g[y][x - 1] == 0 and g[y][x + 1] == 0 and g[y - 1][x] == 1 and g[y + 1][x] == 1
            vert = g[y - 1][x] == 0 and g[y + 1][x] == 0 and g[y][x - 1] == 1 and g[y][x + 1] == 1
            if horiz or vert:
                g[y][x] = 0
    return g


def bfs(grid, start, goal=None):
    """Distances from start; with a goal, returns the path (list of tiles) instead."""
    prev = {start: None}
    queue = [start]
    i = 0
    while i < len(queue):
        cur = queue[i]
        i += 1
        if cur == goal:
            path = []
            while cur != start:
                path.append(cur)
                cur = prev[cur]
            return path[::-1]
        x, y = cur
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < COLS and 0 <= ny < ROWS and grid[ny][nx] == 0 and (nx, ny) not in prev:
                prev[(nx, ny)] = cur
                queue.append((nx, ny))
    if goal is not None:
        return []
    dist = {}
    for cell in queue:  # rebuild distances by walking back
        d, c = 0, cell
        while prev[c] is not None:
            c = prev[c]
            d += 1
        dist[cell] = d
    return dist


def angle_diff(a, b):
    return (a - b + math.pi) % (2 * math.pi) - math.pi


