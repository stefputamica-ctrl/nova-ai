class Game:
    def __init__(self):
        self.state = "title"
        self.t = 0.0
        self.touches = {}
        self.joy_id = None
        self.joy_origin = (0, 0)
        self.joy_pos = (0, 0)
        self.run_id = None
        self.keys_light_pressed = False
        self.title_eyes = []
        if SND.get("drone"):
            SND["drone"].set_volume(0.55)
            SND["drone"].play(-1)
        self.reset()

    # ---- setup ----
    def reset(self):
        self.grid = make_maze()
        self.variant = [[random.random() for _ in range(COLS)] for _ in range(ROWS)]
        self.px, self.py = 1.5, 1.5
        self.dir = 0.0
        self.light = True
        self.battery = 100.0
        self.stamina = 100.0
        self.running = False
        self.flicker = 0.0
        self.candles_got = 0
        self.door_open = False
        self.shake = 0.0
        self.heart_timer = 0.0
        self.growl_timer = 4.0
        self.sting_cool = 0.0
        self.whisper_timer = 8.0
        self.msg = None
        self.msg_t = 0.0
        self.scare_t = 0.0
        self.play_time = 0.0
        self.static_i = 0

        dist = bfs(self.grid, (1, 1))
        cells = sorted(dist, key=lambda c: dist[c])
        far = cells[len(cells) // 3:]
        self.exit = cells[-1]
        picks = [c for c in far if c != self.exit]
        random.shuffle(picks)
        self.candles = []
        for c in picks:
            if all(abs(c[0] - o[0]) + abs(c[1] - o[1]) > 6 for o in self.candles):
                self.candles.append(c)
            if len(self.candles) == CANDLES_NEEDED:
                break
        while len(self.candles) < CANDLES_NEEDED:
            self.candles.append(picks.pop())
        rest = [c for c in cells[5:] if c not in self.candles and c != self.exit]
        self.batteries = random.sample(rest, 6)

        spawn = [c for c in cells if dist[c] > 14 and c != self.exit]
        mx, my = random.choice(spawn)
        self.mx, self.my = mx + 0.5, my + 0.5
        self.m_path = []
        self.m_mode = "wander"
        self.m_memory = 0.0
        self.m_repath = 0.0
        self.m_target = None
        self.m_lit = False
        self.m_seen_before = False
        self.m_dist = 99.0
        self.say("find the 5 candles. turn off your light to hide.", 5)

    def say(self, msg, dur=3.5):
        self.msg = msg
        self.msg_t = dur
        self.msg_dur = dur

    # ---- world helpers ----
    def wall(self, tx, ty):
        if tx < 0 or ty < 0 or tx >= COLS or ty >= ROWS:
            return True
        return self.grid[ty][tx] == 1

    def blocked(self, x, y, r=0.28):
        for tx in (int(x - r), int(x + r)):
            for ty in (int(y - r), int(y + r)):
                if self.wall(tx, ty):
                    return True
        return False

    def ray(self, x, y, ang, maxd, step=0.12):
        dx, dy = math.cos(ang), math.sin(ang)
        d = 0.0
        while d < maxd:
            d += step
            if self.wall(int(x + dx * d), int(y + dy * d)):
                return min(maxd, d + 0.35)  # a bit past the edge so wall faces get lit
        return maxd

    def los(self, x0, y0, x1, y1):
        d = math.hypot(x1 - x0, y1 - y0)
        steps = int(d / 0.2) + 1
        for i in range(1, steps):
            k = i / steps
            if self.wall(int(x0 + (x1 - x0) * k), int(y0 + (y1 - y0) * k)):
                return False
        return True

    def light_on(self):
        return self.light and self.battery > 0 and self.flicker <= 0

    def w2s(self, x, y):
        sx = (x - self.cam_x) * TILE + W / 2 + self.shake_x
        sy = (y - self.cam_y) * TILE + H / 2 + self.shake_y
        return sx, sy

    # ---- input ----
    def pointer_down(self, pid, x, y):
        if self.state == "title":
            self.state = "play"
            return
        if self.state in ("dead", "win"):
            if self.scare_t <= 0:
                self.reset()
                self.state = "play"
            return
        if self.state != "play":
            return
        if math.hypot(x - BTN_LIGHT[0], y - BTN_LIGHT[1]) < BTN_R * 1.2:
            self.toggle_light()
        elif math.hypot(x - BTN_RUN[0], y - BTN_RUN[1]) < BTN_R * 1.2:
            self.run_id = pid
        elif x < W * 0.62 and self.joy_id is None:
            self.joy_id = pid
            self.joy_origin = (x, y)
            self.joy_pos = (x, y)

    def pointer_move(self, pid, x, y):
        if pid == self.joy_id:
            self.joy_pos = (x, y)

    def pointer_up(self, pid):
        if pid == self.joy_id:
            self.joy_id = None
        if pid == self.run_id:
            self.run_id = None

    def toggle_light(self):
        self.light = not self.light
        play("pickup", 0.15)

    # ---- update ----
    def update(self, dt):
        self.t += dt
        if self.msg_t > 0:
            self.msg_t -= dt
        if self.state == "play":
            self.update_play(dt)
        elif self.state in ("dead", "win") and self.scare_t > 0:
            self.scare_t -= dt

    def update_play(self, dt):
        self.play_time += dt
        keys = pygame.key.get_pressed()

        # movement input
        mx = my = 0.0
        if self.joy_id is not None:
            dx = self.joy_pos[0] - self.joy_origin[0]
            dy = self.joy_pos[1] - self.joy_origin[1]
            d = math.hypot(dx, dy)
            if d > JOY_R * 0.15:
                k = min(1.0, d / JOY_R)
                mx, my = dx / d * k, dy / d * k
        kx = (keys[pygame.K_d] or keys[pygame.K_RIGHT]) - (keys[pygame.K_a] or keys[pygame.K_LEFT])
        ky = (keys[pygame.K_s] or keys[pygame.K_DOWN]) - (keys[pygame.K_w] or keys[pygame.K_UP])
        if kx or ky:
            d = math.hypot(kx, ky)
            mx, my = kx / d, ky / d

        want_run = self.run_id is not None or keys[pygame.K_LSHIFT] or keys[pygame.K_RSHIFT]
        moving = mx != 0 or my != 0
        self.running = want_run and moving and self.stamina > 1
        if self.running:
            self.stamina = max(0.0, self.stamina - 33 * dt)
        else:
            self.stamina = min(100.0, self.stamina + (14 if moving else 22) * dt)

        if moving:
            target = math.atan2(my, mx)
            self.dir += angle_diff(target, self.dir) * min(1.0, dt * 10)
            speed = (5.0 if self.running else 2.9) * dt
            nx = self.px + mx * speed
            if not self.blocked(nx, self.py):
                self.px = nx
            ny = self.py + my * speed
            if not self.blocked(self.px, ny):
                self.py = ny

        # flashlight
        if self.light and self.battery > 0:
            self.battery = max(0.0, self.battery - 1.15 * dt)
            if self.battery == 0:
                self.say("the battery is dead...")
        if self.flicker > 0:
            self.flicker -= dt
        elif self.light and self.battery > 0:
            chance = 0.0
            if self.battery < 25:
                chance += 0.05
            if self.m_dist < 5:
                chance += 0.04
            if random.random() < chance:
                self.flicker = random.uniform(0.04, 0.18)

        # pickups
        ptile = (int(self.px), int(self.py))
        if ptile in self.candles:
            self.candles.remove(ptile)
            self.candles_got += 1
            play("chime", 0.8)
            left = CANDLES_NEEDED - self.candles_got
            if left:
                self.say("%d remain... it grows angrier" % left)
            else:
                self.door_open = True
                play("growl", 1.0)
                self.shake = 0.6
                self.say("THE DOOR IS OPEN. RUN.", 5)
        if ptile in self.batteries:
            self.batteries.remove(ptile)
            self.battery = min(100.0, self.battery + 45)
            play("pickup", 0.6)
            self.say("battery +45%", 2)
        if self.door_open and ptile == self.exit:
            self.state = "win"
            self.scare_t = 1.0
            return

        self.update_monster(dt)

        # dread effects
        d = self.m_dist
        if d < 9:
            self.heart_timer -= dt
            if self.heart_timer <= 0:
                k = max(0.0, 1 - d / 9)
                play("heart", 0.25 + 0.75 * k)
                self.heart_timer = 1.25 - 0.9 * k
        if self.m_mode == "chase":
            self.growl_timer -= dt
            if self.growl_timer <= 0:
                play("growl", max(0.2, 1 - d / 10))
                self.growl_timer = random.uniform(3, 6)
        if d < 3:
            self.shake = max(self.shake, (3 - d) * 0.08)
        self.shake = max(0.0, self.shake - dt * 0.8)

        self.whisper_timer -= dt
        if self.whisper_timer <= 0:
            self.say(random.choice(WHISPERS), 3)
            self.whisper_timer = random.uniform(14, 26)

        self.static_i = (self.static_i + 1) % len(STATIC)

        if d < 0.55:
            self.state = "dead"
            self.scare_t = 1.8
            self.shake = 1.0
            play("scream", 1.0)

    def update_monster(self, dt):
        pdx, pdy = self.px - self.mx, self.py - self.my
        self.m_dist = d = math.hypot(pdx, pdy)
        sight = self.los(self.mx, self.my, self.px, self.py)

        # can I see the monster with my flashlight?
        to_m = math.atan2(-pdy, -pdx)
        self.m_lit = (self.light_on() and d < LIGHT_RANGE and sight
                      and abs(angle_diff(to_m, self.dir)) < LIGHT_HALF + 0.1)
        self.sting_cool -= dt
        if self.m_lit and self.sting_cool <= 0:
            play("sting", 0.9)
            self.shake = max(self.shake, 0.3)
            self.sting_cool = 8.0
            if not self.m_seen_before:
                self.m_seen_before = True
                self.say("RUN", 2)

        # can it sense me?
        detect = 9.0 if self.light_on() else 3.2
        if self.running:
            detect += 2.0
        senses = (sight and d < detect) or (self.running and d < 5.5) or d < 1.6
        if senses:
            if self.m_mode != "chase":
                play("growl", 0.9)
            self.m_mode = "chase"
            self.m_memory = 4.0
            self.m_target = (int(self.px), int(self.py))
        elif self.m_mode == "chase":
            self.m_memory -= dt
            if self.m_memory <= 0:
                self.m_mode = "wander"
                self.m_path = []

        speed = 1.8 + 0.15 * self.candles_got
        if self.m_mode == "chase":
            speed = 3.2 + 0.25 * self.candles_got + (0.8 if self.door_open else 0)
        speed *= dt

        if self.m_mode == "chase" and sight and d < detect:
            # straight at you
            if d > 0.01:
                self.mx += pdx / d * min(d, speed)
                self.my += pdy / d * min(d, speed)
            self.m_path = []
            return

        self.m_repath -= dt
        if self.m_mode == "chase" and self.m_repath <= 0:
            self.m_path = bfs(self.grid, (int(self.mx), int(self.my)), self.m_target)
            self.m_repath = 0.3
        if not self.m_path:
            # wander, drifting toward the player's area so it never goes far
            if random.random() < 0.6:
                cx, cy = int(self.px), int(self.py)
                opts = [(x, y) for x in range(cx - 6, cx + 7) for y in range(cy - 6, cy + 7)
                        if not self.wall(x, y)]
            else:
                opts = [(x, y) for y in range(ROWS) for x in range(COLS) if self.grid[y][x] == 0]
            self.m_target = random.choice(opts)
            self.m_path = bfs(self.grid, (int(self.mx), int(self.my)), self.m_target)
        if self.m_path:
            tx, ty = self.m_path[0]
            gx, gy = tx + 0.5, ty + 0.5
            dx, dy = gx - self.mx, gy - self.my
            dd = math.hypot(dx, dy)
            if dd < 0.05:
                self.m_path.pop(0)
            else:
                step = min(dd, speed)
                self.mx += dx / dd * step
                self.my += dy / dd * step

