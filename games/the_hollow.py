def main():
    game = Game()
    while True:
        dt = min(0.05, clock.tick(60) / 1000.0)
        for ev in pygame.event.get():
            if ev.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            elif ev.type == pygame.KEYDOWN:
                if ev.key in (pygame.K_ESCAPE, pygame.K_AC_BACK):
                    pygame.quit()
                    sys.exit()
                if game.state == "play" and ev.key == pygame.K_f:
                    game.toggle_light()
                elif game.state != "play" and ev.key in (pygame.K_SPACE, pygame.K_RETURN):
                    game.pointer_down("key", -1000, -1000)
            elif ev.type == pygame.FINGERDOWN:
                game.pointer_down(ev.finger_id, ev.x * W, ev.y * H)
            elif ev.type == pygame.FINGERMOTION:
                game.pointer_move(ev.finger_id, ev.x * W, ev.y * H)
            elif ev.type == pygame.FINGERUP:
                game.pointer_up(ev.finger_id)
            # mouse events copied from touches are skipped so a tap isn't counted twice
            elif ev.type == pygame.MOUSEBUTTONDOWN and not getattr(ev, "touch", False) and ev.button == 1:
                game.pointer_down("mouse", *ev.pos)
            elif ev.type == pygame.MOUSEMOTION and not getattr(ev, "touch", False):
                game.pointer_move("mouse", *ev.pos)
            elif ev.type == pygame.MOUSEBUTTONUP and not getattr(ev, "touch", False) and ev.button == 1:
                game.pointer_up("mouse")
        game.update(dt)
        game.draw()
        pygame.display.flip()


if __name__ == "__main__":
    main()
